import Foundation

/// Generates the zsh launchers in `~/.code-island/bin/` that Claude Code and
/// Codex hooks invoke (`code-island-bridge`, `code-island-codex-bridge`).
///
/// A launcher resolves the `CodeIslandBridge` helper binary in this order:
///   1. the currently running app bundle (`Bundle.main.bundlePath`)
///   2. `/Applications/SuperNotch.app`
///   3. `$HOME/Applications/SuperNotch.app`
///   4. `/Applications/Code Island.app`, then `$HOME/Applications/Code Island.app`
///      (fallback for existing Code Island users)
/// and otherwise prints an error to stderr and exits 127.
///
/// Hook entries keep pointing at the same launcher paths CI used, so the
/// installers' "isOurs" detection (`command` contains "code-island") replaces
/// existing Code Island entries in place instead of duplicating them.
enum AIBridgeLauncher {
    /// Bundle-relative path of the embedded bridge helper.
    static let helperRelativePath = "/Contents/Helpers/CodeIslandBridge"

    static var binDirectory: URL {
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".code-island/bin")
    }

    /// Absolute path of the launcher named `name` (e.g. "code-island-bridge").
    static func launcherPath(_ name: String) -> String {
        binDirectory.appendingPathComponent(name).path
    }

    /// Quote `value` for zsh. Plain tokens are returned unchanged; anything
    /// else is wrapped in single quotes with embedded quotes escaped.
    static func shellQuote(_ value: String) -> String {
        let safe = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-./=:@%+,")
        if !value.isEmpty, value.unicodeScalars.allSatisfy({ safe.contains($0) }) {
            return value
        }
        return "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// The launcher script body for `name`, forwarding `extraArgs` (e.g.
    /// `["--source", "codex"]`) before the hook's own arguments.
    static func script(name: String, extraArgs: [String], currentBundlePath: String = Bundle.main.bundlePath) -> String {
        let args = (extraArgs.map(shellQuote) + ["\"$@\""]).joined(separator: " ")
        // Always single-quote the running bundle path, even when it is a plain
        // token, so the generated script reads uniformly.
        let current = "'" + currentBundlePath.replacingOccurrences(of: "'", with: "'\\''") + "'"
        let candidates = [
            current,
            "\"/Applications/SuperNotch.app\"",
            "\"$HOME/Applications/SuperNotch.app\"",
            "\"/Applications/Code Island.app\"",
            "\"$HOME/Applications/Code Island.app\"",
        ].joined(separator: " ")
        return [
            "#!/bin/zsh",
            "# \(name) launcher (auto-generated by SuperNotch; compatible with Code Island)",
            "H=\(helperRelativePath)",
            "for P in \(candidates); do",
            "  B=\"${P}${H}\"; [ -x \"$B\" ] && exec \"$B\" \(args)",
            "done",
            "echo \"\(name): SuperNotch (or Code Island) app not found.\" >&2",
            "exit 127",
            "",
        ].joined(separator: "\n")
    }

    /// Write (or refresh) the launcher `name` and make it executable.
    /// Skips the write when the content is already current.
    @discardableResult
    static func install(name: String, extraArgs: [String] = []) -> Bool {
        let fm = FileManager.default
        do {
            try fm.createDirectory(at: binDirectory, withIntermediateDirectories: true)
        } catch {
            Log.error("AIBridgeLauncher: can't create \(binDirectory.path): \(error)")
            return false
        }
        let url = binDirectory.appendingPathComponent(name)
        let body = script(name: name, extraArgs: extraArgs)
        if (try? String(contentsOf: url, encoding: .utf8)) != body {
            do {
                try body.write(to: url, atomically: true, encoding: .utf8)
            } catch {
                Log.error("AIBridgeLauncher: failed to write \(url.path): \(error)")
                return false
            }
        }
        do {
            try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: url.path)
        } catch {
            Log.error("AIBridgeLauncher: failed to chmod \(url.path): \(error)")
            return false
        }
        return true
    }

    /// True when the hooks JSON at `url` (Claude settings.json or Codex
    /// hooks.json — both use `{"hooks": {event: [{"hooks": [{"command": …}]}]}}`)
    /// contains at least one Code Island entry. Read-only.
    static func hooksFileContainsOurs(_ url: URL) -> Bool {
        guard let data = try? Data(contentsOf: url), !data.isEmpty,
              let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
              let hooks = root["hooks"] as? [String: Any] else { return false }
        for case let entries as [[String: Any]] in hooks.values {
            for entry in entries {
                guard let inner = entry["hooks"] as? [[String: Any]] else { continue }
                if inner.contains(where: { ($0["command"] as? String)?.contains("code-island") == true }) {
                    return true
                }
            }
        }
        return false
    }
}
